// installUpdateAsset dispatches installation of a downloaded update asset
// based on its file type (Linux-specific formats).
func (a *App) installUpdateAsset(localPath string) error {
	lower := strings.ToLower(localPath)
	switch {
	case strings.HasSuffix(lower, ".tar.gz"):
		return a.installTarGz(localPath)
	default:
		return fmt.Errorf("unsupported update file type: %s", localPath)
	}
}

// installTarGz replaces the running application with the contents of a
// .tar.gz release bundle. The archive may contain a top-level directory
// (e.g. SniShaper/); the binary and payload are located inside and copied
// over the install directory. User data under ~/.config/snishaper is never
// touched.
//
// The copy and relaunch run in a detached shell, not in this process: the
// binary cannot be replaced while the process holds it, and anything still
// running inside this process dies with it. So this function extracts and
// stages the payload, spawns the applier, then shuts the app down
// gracefully (TUN, system proxy, core all go through QuitApp) — the applier
// waits for this process to disappear, applies the payload and relaunches.
func (a *App) installTarGz(localPath string) error {
	execPath, err := os.Executable()
	if err != nil {
		return fmt.Errorf("cannot locate application directory: %v", err)
	}
	execDir := filepath.Dir(execPath)
	if !isDirWritable(execDir) {
		return fmt.Errorf("dir_not_writable")
	}

	base := filepath.Join(os.TempDir(), "snishaper-update")
	stage := filepath.Join(base, "stage")
	os.RemoveAll(base)
	if err := os.MkdirAll(stage, 0755); err != nil {
		return err
	}

	// 1. Extract the bundle into a staging directory.
	a.appendLog("[update] Extracting update bundle...")
	if err := extractTarGz(localPath, stage); err != nil {
		os.RemoveAll(base)
		return fmt.Errorf("extract update bundle: %w", err)
	}
	stageRoot := findStageRoot(stage)
	if stageRoot == "" {
		os.RemoveAll(base)
		return fmt.Errorf("update bundle is empty or malformed")
	}

	// 2. Schedule the apply + relaunch in a detached applier.
	a.appendLog("[update] Scheduling detached update applier...")
	if err := spawnUpdateApplier(execPath, base, stageRoot, execDir, os.Getpid()); err != nil {
		os.RemoveAll(base)
		return fmt.Errorf("schedule update applier: %w", err)
	}

	// 3. Shut down gracefully so files free up; the applier takes over.
	a.appendLog("[update] Stopping SniShaper; the update applies after exit")
	a.QuitApp()
	return nil
}

// spawnUpdateApplier starts a detached shell that waits for the current
// process to exit (bounded, so a hung app cannot leave the applier looping
// forever), copies the staged payload over the install directory, relaunches
// and removes the staging directory. Progress lands in <base>/apply.log.
func spawnUpdateApplier(execPath, base, stageRoot, execDir string, pid int) error {
	script := filepath.Join(base, "apply-update.sh")
	content := buildUpdateApplyScript(pid, stageRoot, execDir, execPath, base)
	if err := os.WriteFile(script, []byte(content), 0755); err != nil {
		return err
	}
	cmd := exec.Command("/bin/sh", script)
	cmd.SysProcAttr = &syscall.SysProcAttr{Setsid: true}
	if err := cmd.Start(); err != nil {
		return err
	}
	// Detach: let the applier outlive this process.
	_ = cmd.Process.Release()
	return nil
}

// buildUpdateApplyScript renders the applier shell script. Single quotes are
// the only safe envelope for arbitrary install paths, so every interpolated
// path goes through shQuote.
func buildUpdateApplyScript(pid int, stageRoot, execDir, execPath, base string) string {
	return `#!/bin/sh
# Generated by SniShaper self-update: wait for the app to exit, apply the
# staged payload, relaunch, clean up.
exec >> '` + shQuote(base) + `'/apply.log 2>&1
echo "[apply-update] waiting for pid ` + fmt.Sprintf("%d", pid) + ` to exit"
n=0
while kill -0 ` + fmt.Sprintf("%d", pid) + ` 2>/dev/null; do
    sleep 0.2
    n=$((n+1))
    if [ "$n" -ge 300 ]; then
        echo "[apply-update] app did not exit within 60s, aborting"
        exit 3
    fi
done
echo "[apply-update] applying update"
cp -a '` + shQuote(stageRoot) + `'/. '` + shQuote(execDir) + `'/ || exit 2
echo "[apply-update] relaunching SniShaper"
sleep 1
'` + shQuote(execPath) + `' --startup >/dev/null 2>&1 &
echo "[apply-update] done"
sleep 2
rm -rf '` + shQuote(base) + `'
`
}

// shQuote wraps s in single quotes for /bin/sh, escaping embedded quotes.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// extractTarGz extracts a gzipped tar archive into dest, guarding against
// path traversal.
func extractTarGz(src, dest string) error {
	f, err := os.Open(src)
	if err != nil {
		return err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		return err
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		target := filepath.Join(dest, hdr.Name)
		if !strings.HasPrefix(target, filepath.Clean(dest)+string(filepath.Separator)) {
			return fmt.Errorf("archive path escapes destination: %s", hdr.Name)
		}
		switch hdr.Typeflag {
		case tar.TypeDir:
			if err := os.MkdirAll(target, 0755); err != nil {
				return err
			}
		case tar.TypeReg:
			if err := os.MkdirAll(filepath.Dir(target), 0755); err != nil {
				return err
			}
			out, err := os.OpenFile(target, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, os.FileMode(hdr.Mode)&0777)
			if err != nil {
				return err
			}
			if _, err := io.Copy(out, tr); err != nil {
				out.Close()
				return err
			}
			out.Close()
		}
	}
}

